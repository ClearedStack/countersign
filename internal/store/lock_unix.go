//go:build unix

package store

import (
	"os"
	"syscall"
)

// lock takes the store's one exclusive lock. The command line and the worker
// are separate processes working on the same directory, and every change
// either of them makes happens under this lock.
func lock(path string) (unlock func(), err error) {
	f, err := os.OpenFile(path, os.O_CREATE|os.O_RDWR, 0o600)
	if err != nil {
		return nil, err
	}
	if err := syscall.Flock(int(f.Fd()), syscall.LOCK_EX); err != nil {
		f.Close()
		return nil, err
	}
	return func() {
		syscall.Flock(int(f.Fd()), syscall.LOCK_UN)
		f.Close()
	}, nil
}
